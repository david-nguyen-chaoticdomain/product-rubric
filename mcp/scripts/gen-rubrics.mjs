#!/usr/bin/env node
/**
 * Generate src/rubrics.generated.ts: the shipped rubric files embedded
 * as a record of id -> full file text. Used by the hosted Worker and as
 * the local package's built-in library.
 *
 * Run automatically by `npm run build` and `npm run deploy`. The output
 * is a gitignored build artifact: it is regenerated on every build and
 * deploy, never committed.
 *
 * Usage: node scripts/gen-rubrics.mjs [rubricsDir]
 * Default rubricsDir: ../rubrics relative to this package (the repo layout).
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const rubricsDir = process.argv[2]
  ? resolve(process.argv[2])
  : resolve(here, "../../rubrics");
const outFile = resolve(here, "../src/rubrics.generated.ts");

const rubricsData = {};
for (const entry of readdirSync(rubricsDir).sort()) {
  const categoryPath = join(rubricsDir, entry);
  if (!statSync(categoryPath).isDirectory()) continue;
  for (const file of readdirSync(categoryPath).sort()) {
    if (!file.endsWith(".md") || file.startsWith("_")) continue;
    rubricsData[file.slice(0, -3)] = readFileSync(
      join(categoryPath, file),
      "utf8",
    );
  }
}

const ids = Object.keys(rubricsData);
const lines = [
  "/**",
  " * GENERATED by scripts/gen-rubrics.mjs. Do not edit by hand.",
  ` * Embedded copies of the ${ids.length} shipped rubric files, for the`,
  " * hosted Worker and the local package's built-in library.",
  " */",
  "",
  "export const RUBRICS: Record<string, string> = {",
  ...ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(rubricsData[id])},`),
  "};",
  "",
];
writeFileSync(outFile, lines.join("\n"));
console.log(`gen-rubrics: embedded ${ids.length} rubrics from ${rubricsDir}`);
